// Helper function to generate card image paths dynamically
function getCardImagePath(card) {
  if (!card) return '';
  
  if (card.type === '天罡卡' || card.type === '地煞卡') {
    const paddedId = String(card.id).padStart(3, '0');
    if (card.originalImage) {
      return `./assets/images/${card.originalImage}`;
    }
    return `./assets/images/EF_${paddedId}_${card.name}.png`;
  } else if (card.type === '重大戰役' || card.type === '重大戰役卡') {
    const match = card.id.match(/\d+/);
    const num = match ? match[0].padStart(3, '0') : '001';
    return `./assets/images/MAC_${num}.png`;
  } else if (card.type === '小型戰役' || card.type === '小型戰役卡') {
    const match = card.id.match(/\d+/);
    const num = match ? match[0].padStart(3, '0') : '001';
    return `./assets/images/MC_${num}.png`;
  }
  
  return '';
}

// Helper function to get card back image path
function getCardBackPath(type) {
  if (type === '天罡卡') return './assets/images/天罡卡牌背.png';
  if (type === '地煞卡') return './assets/images/地煞卡牌背.png';
  if (type === '重大戰役' || type === '重大戰役卡') return './assets/images/大型戰役牌背.png';
  if (type === '小型戰役' || type === '小型戰役卡') return './assets/images/小型戰役牌背.png';
  return '';
}
